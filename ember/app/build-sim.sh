#!/bin/bash
# Builds the app for the iOS Simulator on an Apple Silicon Mac, into
# app/.build-sim/Ember.app. The same sources as build.sh, compiled for the
# Simulator, with the Simulator build of the emulator library.
#
# Left out on purpose: the icon, and the helpers that travel into the guest.
# The app runs without them, and they are not what this build is for.
set -euo pipefail
unset DYLD_LIBRARY_PATH DYLD_FALLBACK_LIBRARY_PATH

ROOT="$(cd "$(dirname "$0")" && pwd)"
BUILD="$ROOT/.build-sim"
APP="$BUILD/Ember.app"
SDK="$(xcrun --sdk iphonesimulator --show-sdk-path)"
TARGET="arm64-apple-ios16.0-simulator"
DYLIB="${INFERNO_SIM_DYLIB:-$ROOT/../build/inferno-sim/libqemu-aarch64-softmmu.dylib}"
KEYMAPS="${INFERNO_KEYMAPS:-/opt/homebrew/share/qemu/keymaps}"

[ -f "$DYLIB" ] || { echo "No Simulator emulator library at $DYLIB" >&2; exit 1; }
[ -d "$KEYMAPS" ] || { echo "No keymaps at $KEYMAPS (brew install qemu)" >&2; exit 1; }

rm -rf "$BUILD"
mkdir -p "$APP/Frameworks" "$APP/qemu-data"

echo "==> Compiling for the Simulator"
STAMP="$(date '+%Y-%m-%d %H:%M:%S')"
cat > "$ROOT/Sources/BuildInfo.swift" <<INFO
// Generated by build-sim.sh — do not edit.
enum BuildInfo {
    static let stamp = "$STAMP (simulator)"
}
INFO
xcrun --sdk iphonesimulator swiftc \
    -target "$TARGET" \
    -sdk "$SDK" \
    -Onone -g \
    -parse-as-library \
    -o "$APP/Inferno" \
    "$ROOT"/Sources/*.swift

echo "==> Bundle"
cp "$ROOT/Resources/Info.plist" "$APP/Info.plist"
/usr/libexec/PlistBuddy -c "Add :CFBundleSupportedPlatforms array" \
    -c "Add :CFBundleSupportedPlatforms:0 string iPhoneSimulator" "$APP/Info.plist"
cp "$DYLIB" "$APP/Frameworks/"
cp -R "$KEYMAPS" "$APP/qemu-data/keymaps"
chmod +x "$APP/Inferno"

echo "==> Signing"
codesign --force --sign - --timestamp=none "$APP/Frameworks/$(basename "$DYLIB")"
codesign --force --sign - --timestamp=none "$APP"

echo "Built: $APP"
